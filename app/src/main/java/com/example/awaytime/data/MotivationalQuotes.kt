    private var lastIndex = -1

    /**
     * Returns a random quote ensuring consecutive calls don't return the exact same quote.
     */
    fun getRandomQuote(): String {
        if (quotes.size <= 1) return quotes.first()
        var newIndex: Int
        do {
            newIndex = Random.nextInt(quotes.size)
        } while (newIndex == lastIndex)
        lastIndex = newIndex
        return quotes[newIndex]
    }
